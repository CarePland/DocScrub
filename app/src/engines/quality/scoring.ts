/** Rule name -> full, unsplit set of dictionary entries. Matches Python's
 *  `QUALITY_DICTIONARIES` exactly (used directly by _shape_rules and
 *  _single_token_classifications below -- NOT the single/phrase split,
 *  which is a separate index only _dictionary_rules uses). Key iteration
 *  order matches Python's real dict insertion order (see
 *  quality-dictionaries.data.ts's own header note) -- this matters because
 *  _dictionary_rules below iterates these keys to build an ordered
 *  `classifications` list that flows into QualityResult.reasons. */
const QUALITY_DICTIONARY_KEYS: string[] = Object.keys(QUALITY_DICTIONARIES_DATA);
const QUALITY_DICTIONARIES = new Map<string, Set<string>>(
  QUALITY_DICTIONARY_KEYS.map((rule) => [rule, new Set(QUALITY_DICTIONARIES_DATA[rule])])
);

// def _dictionary_index(dictionaries) -> (single_terms, phrase_terms):
function splitTerms(entries: Set<string>): { single: Set<string>; phrase: Set<string> } {
  const single = new Set<string>();
  const phrase = new Set<string>();
  for (const entry of entries) {
    (entry.includes(" ") ? phrase : single).add(entry);
  }
  return { single, phrase };
}

const QUALITY_SINGLE_TERMS = new Map<string, Set<string>>();
const QUALITY_PHRASE_TERMS = new Map<string, Set<string>>();
for (const [rule, entries] of QUALITY_DICTIONARIES) {
  const { single, phrase } = splitTerms(entries);
  QUALITY_SINGLE_TERMS.set(rule, single);
  QUALITY_PHRASE_TERMS.set(rule, phrase);
}

const COMMON_DICTIONARY_EXCLUSIONS_SET = new Set(COMMON_DICTIONARY_EXCLUSIONS);
// ALL_COMMON_DICTIONARY_WORDS = set().union(*(single terms for rules not excluded))
const ALL_COMMON_DICTIONARY_WORDS = new Set<string>();
for (const [rule, single] of QUALITY_SINGLE_TERMS) {
  if (COMMON_DICTIONARY_EXCLUSIONS_SET.has(rule)) continue;
  for (const term of single) ALL_COMMON_DICTIONARY_WORDS.add(term);
}

