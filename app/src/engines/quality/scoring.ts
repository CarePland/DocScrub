/** Substitute for Python's `_is_heading_like`'s `"header" in
 *  normalize_lexicon_entry(occurrence.location)` check -- see this file's
 *  doc comment, point 2. `blocksById` must contain every block referenced
 *  by `occurrences[].blockId`. */
// def _is_heading_like(candidate: Candidate) -> bool:
function isHeadingLike(occurrences: Occurrence[], blocksById: ReadonlyMap<string, ContentBlock>): boolean {
  for (const occurrence of occurrences) {
    const block = blocksById.get(occurrence.blockId);
    const context = occurrence.context;
    if (block?.kind === "header" || normalizeLexiconEntry(context).includes("subject")) {
      return true;
    }
    const bare = context.replace(/\[/g, "").replace(/\]/g, "").trim();
    if (bare && bare.toUpperCase() === bare && bare.length > 8) {
      return true;
    }
  }
  return false;
}

// def _appears_in_email(candidate: Candidate) -> bool:
function appearsInEmail(displayValue: string, occurrences: Occurrence[]): boolean {
  const candidateTokens = normalizedTokenSet(displayValue);
  if (candidateTokens.size === 0) return false;
  for (const occurrence of occurrences) {
    for (const match of occurrence.context.matchAll(EMAIL_RE)) {
      const email = match[0];
      const emailTokens = new Set<string>();
      for (const tokenMatch of email.matchAll(EMAIL_LOCAL_TOKEN_RE)) {
        emailTokens.add(normalizeLexiconEntry(tokenMatch[0]));
      }
      for (const t of candidateTokens) {
        if (emailTokens.has(t)) return true;
      }
    }
  }
  return false;
}

// def _near_title(candidate: Candidate) -> bool:
function nearTitle(occurrences: Occurrence[]): boolean {
  for (const occurrence of occurrences) {
    const context = occurrence.context;
    const bracketIndex = context.indexOf("[");
    const sliceEnd = bracketIndex >= 0 ? bracketIndex : context.length;
    const before = context.slice(0, sliceEnd);
    if (NEAR_TITLE_BEFORE_RE.test(before) || TITLE_RE.test(context)) {
      return true;
    }
  }
  return false;
}

const SIGNATURE_MARKERS = ["signature", "regards,", "sincerely,", "from:", "sent:"];

// def _signature_evidence(candidate: Candidate) -> bool:
function signatureEvidence(displayValue: string, occurrences: Occurrence[]): boolean {
  const text = normalizeLexiconEntry(displayValue);
  for (const occurrence of occurrences) {
    const context = normalizeLexiconEntry(occurrence.context);
    if (SIGNATURE_MARKERS.some((marker) => context.includes(marker)) && context.includes(text)) {
      return true;
    }
  }
  return false;
}

// def _positive_evidence(candidate: Candidate) -> list[str]:
function positiveEvidence(candidate: Candidate, occurrences: Occurrence[]): string[] {
  const reasons: string[] = [];
  if (candidate.detectedType !== "person") reasons.push("deterministic_non_person_type");
  if (appearsInEmail(candidate.displayValue, occurrences)) reasons.push("email_address_evidence");
  if (nearTitle(occurrences)) reasons.push("nearby_title");
  if (signatureEvidence(candidate.displayValue, occurrences)) reasons.push("signature_or_email_header_context");
  return reasons;
}

// ---- Dictionary / shape / acronym classification (lines 721-816) ------

// def _dictionary_rules(text: str, tokens: set[str]) -> list[str]:
function dictionaryRules(text: string, tokenSet: Set<string>): string[] {
  const folded = normalizedText(text);
  const rules: string[] = [];
  for (const rule of QUALITY_DICTIONARY_KEYS) {
    const phraseTerms = QUALITY_PHRASE_TERMS.get(rule);
    if (phraseTerms?.has(folded)) {
      rules.push(rule);
      continue;
    }
    const singleTerms = QUALITY_SINGLE_TERMS.get(rule);
    if (singleTerms) {
      for (const t of tokenSet) {
        if (singleTerms.has(t)) {
          rules.push(rule);
          break;
        }
      }
    }
  }
  return rules;
}

// def _is_likely_acronym(text: str) -> bool:
function isLikelyAcronym(text: string): boolean {
  const compact = text.normalize("NFKC").trim().replace(/\s+/g, "");
  if (!compact || TITLECASE_WORD_RE.test(compact)) return false;
  return ACRONYM_RE.test(compact);
}

// def _acronym_classifications(text: str) -> list[str]:
function acronymClassifications(text: string): string[] {
  return isLikelyAcronym(text) ? ["likely_acronym"] : [];
}

// def _shape_rules(text, tokens, token_set) -> list[str]:
function shapeRules(text: string, tokenList: string[], tokenSet: Set<string>): string[] {
  const rules: string[] = [];
  if (tokenList.length === 0) {
    rules.push("no_alpha_tokens");
    return rules;
  }
  if (isLikelyAcronym(text)) return rules;
  if (BAD_CAPS_RE.test(text)) rules.push("implausible_capitalization");

  const sentenceFragmentWords = QUALITY_DICTIONARIES.get("sentence_fragment_word") ?? new Set<string>();
  let fragmentOverlap = 0;
  for (const t of tokenSet) if (sentenceFragmentWords.has(t)) fragmentOverlap++;
  if (tokenList.length >= 2 && fragmentOverlap >= 1) rules.push("sentence_fragment");

  if (tokenSet.size > 0 && [...tokenSet].every((t) => ALL_COMMON_DICTIONARY_WORDS.has(t))) {
    rules.push("all_common_dictionary_words");
  }
  if (tokenList.length > 4) rules.push("grammatical_phrase_shape");
  if (tokenList.length === 1 && (tokenList[0]?.length ?? 0) <= 2) rules.push("too_short_single_token");
  if (OCR_ARTIFACT_RE.test(text) && !isLikelyAcronym(text)) rules.push("ocr_artifact");
  return rules;
}

// def _single_token_classifications(text, tokens, token_set) -> list[str]:
function singleTokenClassifications(text: string, tokenList: string[], tokenSet: Set<string>): string[] {
  if (tokenList.length !== 1) return [];
  const token = tokenSet.values().next().value ?? "";
  const has = (rule: string): boolean => QUALITY_DICTIONARIES.get(rule)?.has(token) ?? false;
  const classifications: string[] = [];

  if (KNOWN_GIVEN_NAMES_SET.has(token) || has("known_first_name")) classifications.push("known_first_name");
  if (KNOWN_SURNAMES_SET.has(token) || has("known_surname")) classifications.push("known_surname");
  if (has("common_english_word")) classifications.push("common_english_word");
  if (has("address_suffix")) classifications.push("address_suffix");
  if (has("calendar_abbreviation")) classifications.push("calendar_abbreviation");
  if (has("common_abbreviation")) classifications.push("common_abbreviation");
  if (has("contraction")) classifications.push("contraction");
  if (has("expanded_common_language_token")) classifications.push("expanded_common_language_token");
  if (has("interjection_casual")) classifications.push("interjection_casual");
  if (has("institution_acronym")) classifications.push("institution_acronym");
  if (has("product_system_name")) classifications.push("product_system_name");
  if (has("department_organization")) classifications.push("department_organization");
  if (has("honorific_title")) classifications.push("honorific_title");
  if (has("professional_credential")) classifications.push("professional_credential");
  if (has("organization_suffix")) classifications.push("organization_suffix");
  if (has("document_structure_term")) classifications.push("document_structure_term");
  if (has("legal_administrative_term")) classifications.push("legal_administrative_term");
  if (OCR_ARTIFACT_RE.test(text) && !isLikelyAcronym(text)) classifications.push("ocr_artifact");
  if (isLikelyAcronym(text)) classifications.push("likely_acronym");

  if (classifications.length === 0) {
    if (/^[A-Z]/.test(text)) classifications.push("unknown_capitalized_token");
    else if (/^[a-z]/.test(text)) classifications.push("unknown_lowercase_token");
    else classifications.push("unknown_token");
  }
  return classifications;
}

interface QualityEvidence {
  classifications: string[];
  positive: string[];
  negative: string[];
}

// def _quality_evidence(candidate, text, tokens, token_set) -> QualityEvidence:
function qualityEvidence(
  candidate: Candidate,
  occurrences: Occurrence[],
  text: string,
  tokenList: string[],
  tokenSet: Set<string>
): QualityEvidence {
  const positive = positiveEvidence(candidate, occurrences);
  const acronymRules = acronymClassifications(text);
  let dictRules = dictionaryRules(text, tokenSet);
  if (acronymRules.length > 0) {
    dictRules = dictRules.filter((r) => r !== "sentence_fragment_word");
  }
  const shapeRulesResult = shapeRules(text, tokenList, tokenSet);
  const singleTokenRules = singleTokenClassifications(text, tokenList, tokenSet);

  let classifications = dedupe([...dictRules, ...shapeRulesResult, ...acronymRules, ...singleTokenRules]);

  if (tokenList.length > 1 || classifications.includes("ambiguous_lexical_token")) {
    classifications = classifications.filter((r) => r !== "expanded_common_language_token");
  }
  const unknownFallbackRules = new Set(["unknown_capitalized_token", "unknown_lowercase_token", "unknown_token"]);
  if (classifications.some((r) => !unknownFallbackRules.has(r))) {
    classifications = classifications.filter((r) => !unknownFallbackRules.has(r));
  }

  const promoted = classifications.filter((r) => r === "known_first_name" || r === "known_surname");
  const positiveFull = dedupe([...positive, ...promoted]);
  const negative = dedupe(classifications.filter((r) => NEGATIVE_FILTER_RULES_SET.has(r)));

  return { classifications, positive: positiveFull, negative };
}

