// Python's str.title(): here every input is already lowercase snake_case
// with underscores replaced by spaces, so uppercasing each word's first
// letter is behaviorally identical for every real input this sees.
function titleCase(value: string): string {
  return value.replace(/\b\w/g, (c) => c.toUpperCase());
}

// def _evidence_label(rule: str) -> str:
function evidenceLabel(rule: string): string {
  return EXPLICIT_EVIDENCE_LABELS[rule] ?? titleCase(rule.replace(/_/g, " "));
}

// def _score_from_evidence(reasons: list[str]) -> tuple[int, list[dict]]:
function scoreFromEvidence(
  reasons: string[],
  weights: Record<string, number>
): { score: number; breakdown: EvidenceContribution[] } {
  const uniqueReasons = dedupe(reasons);
  const contributions: EvidenceContribution[] = uniqueReasons.map((reason) => ({
    rule: reason,
    label: evidenceLabel(reason),
    weight: weights[reason] ?? 0,
  }));
  const rawScore = 35 + contributions.reduce((sum, c) => sum + c.weight, 0);
  const score = Math.max(1, Math.min(99, rawScore));
  return { score, breakdown: contributions };
}

// def _status_from_score(score: int) -> str:
function statusFromScore(score: number, reviewThreshold: number): Recommendation {
  return score >= reviewThreshold ? "ToReview" : "Unlikely";
}

// def _quality_from_score(score: int) -> str:
function qualityFromScore(score: number, reviewThreshold: number): QualityLabel {
  if (score >= 80) return "Strong";
  if (score >= reviewThreshold) return "Possible";
  return "Unlikely";
}

interface ScoredResultArgs {
  reasons: string[];
  explanation: string;
  suggestedType?: string | undefined;
  positiveReasons?: string[];
  filterRules?: string[];
}

// def _scored_result(*, reasons, explanation, suggested_type=None, positive_reasons=None, filter_rules=None) -> QualityResult:
function scoredResult(args: ScoredResultArgs, weights: Record<string, number>, reviewThreshold: number): ScoredQuality {
  const uniqueReasons = dedupe(args.reasons);
  const { score, breakdown } = scoreFromEvidence(uniqueReasons, weights);
  return {
    quality: qualityFromScore(score, reviewThreshold),
    reasons: uniqueReasons,
    explanation: args.explanation,
    suggestedType: args.suggestedType,
    status: statusFromScore(score, reviewThreshold),
    score,
    evidenceBreakdown: breakdown,
    positiveReasons: dedupe(args.positiveReasons ?? []),
    filterRules: dedupe(args.filterRules ?? []),
  };
}

// def _filter_result(candidate, base_reasons, filter_rules, evidence_rules=None) -> QualityResult:
// `candidate` param dropped -- Python's own implementation never reads it.
function filterResult(
  baseReasons: string[],
  filterRulesArg: string[],
  weights: Record<string, number>,
  reviewThreshold: number,
  evidenceRulesArg?: string[]
): ScoredQuality {
  // Python: `evidence = evidence_rules or filter_rules` -- `or` falls back
  // on both None AND an empty list, since both are falsy in Python.
  const evidenceRules = evidenceRulesArg && evidenceRulesArg.length > 0 ? evidenceRulesArg : filterRulesArg;
  return scoredResult(
    {
      reasons: [...baseReasons, ...evidenceRules, "no_positive_person_evidence"],
      explanation: "Deterministic evidence gives this candidate low review priority",
      filterRules: evidenceRules,
    },
    weights,
    reviewThreshold
  );
}

