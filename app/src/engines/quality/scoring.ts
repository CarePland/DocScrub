/**
 * Faithful port of `score_candidate_quality(candidate)`. See this file's
 * top doc comment for why the signature differs from Python's
 * single-argument version (shape differences #1 and #2).
 *
 * @param candidate the candidate being scored (detectedType, displayValue)
 * @param occurrences exactly this candidate's occurrences -- the caller
 *   must group DetectionResult.occurrences by candidateId before calling
 *   (see CandidateQualityEngine.ts). Order does not affect the result:
 *   every occurrence-scanning helper here uses "any occurrence matches"
 *   semantics, same as Python's iteration.
 * @param blocksById every ContentBlock referenced by
 *   occurrences[].blockId, keyed by id -- substitutes for Python's
 *   per-occurrence location string (shape difference #2).
 * @param weights defaults to the ported Python EVIDENCE_WEIGHTS constants;
 *   pass ScoringProfileSnapshot.weights for profile-driven, reproducible
 *   scoring (shape difference #4 / ADR-015).
 * @param reviewThreshold defaults to the ported Python
 *   STATUS_THRESHOLDS[REVIEW]; pass ScoringProfileSnapshot.thresholds[...] .
 */
export function scoreCandidateQuality(
  candidate: Candidate,
  occurrences: Occurrence[],
  blocksById: ReadonlyMap<string, ContentBlock>,
  weights: Record<string, number> = DEFAULT_EVIDENCE_WEIGHTS,
  reviewThreshold: number = DEFAULT_REVIEW_THRESHOLD
): ScoredQuality {
  if (candidate.detectedType !== "person") {
    return scoredResult(
      {
        reasons: ["deterministic_non_person_type"],
        explanation: "Deterministic non-person detector",
        positiveReasons: ["deterministic_non_person_type"],
      },
      weights,
      reviewThreshold
    );
  }

  const text = candidate.displayValue.trim().replace(/\s+/g, " ");
  const folded = normalizedText(text);
  const tokenList = tokens(text);
  const tokenSet = normalizedTokenSet(text);
  const reasons: string[] = [];
  let suggestedType: string | undefined;

  const count = occurrences.length;
  if (count === 1) reasons.push("single_occurrence");
  else if (count === 2) reasons.push("small_frequency_bonus");
  else if (count <= 5) reasons.push("moderate_frequency_bonus");
  else reasons.push("frequency_saturated");

  const evidence = qualityEvidence(candidate, occurrences, text, tokenList, tokenSet);
  const positiveReasons = evidence.positive;
  const classifications = evidence.classifications;
  const filterRules = evidence.negative;

  if (SUGGESTED_ORGANIZATION_PHRASES.has(folded)) {
    suggestedType = "organization";
  }

  const hasAmbiguousNameEvidence = classifications.includes("ambiguous_lexical_token");
  const hasProtectiveSingleTokenEvidence =
    tokenList.length === 1 && classifications.some((r) => PROTECTIVE_SINGLE_TOKEN_EVIDENCE_RULES_SET.has(r));
  const onlySoftAmbiguousNegatives = filterRules.every((r) => AMBIGUOUS_NAME_SOFT_NEGATIVES_SET.has(r));

  if (
    filterRules.length > 0 &&
    positiveReasons.length === 0 &&
    !((hasAmbiguousNameEvidence || hasProtectiveSingleTokenEvidence) && onlySoftAmbiguousNegatives)
  ) {
    return filterResult(reasons, filterRules, weights, reviewThreshold, classifications);
  }

  if (LAST_FIRST_RE.test(text)) {
    return scoredResult(
      {
        reasons: [...reasons, ...positiveReasons, ...classifications, "surname_given_structure"],
        explanation: "Strong surname, given-name structure",
        positiveReasons: [...positiveReasons, "surname_given_structure"],
        filterRules: classifications,
      },
      weights,
      reviewThreshold
    );
  }

  if (SURNAME_INITIALS_RE.test(text) || INITIAL_SURNAME_RE.test(text)) {
    return scoredResult(
      {
        reasons: [...reasons, ...positiveReasons, ...classifications, "initials_with_surname"],
        explanation: "Strong surname and initials structure",
        positiveReasons: [...positiveReasons, "initials_with_surname"],
        filterRules: classifications,
      },
      weights,
      reviewThreshold
    );
  }

  if (TWO_NAME_RE.test(text)) {
    const structureReasons = ["strong_name_structure"];
    let hasKnownGivenNameToken = false;
    for (const t of tokenSet) {
      if (KNOWN_GIVEN_NAMES_SET.has(t)) {
        hasKnownGivenNameToken = true;
        break;
      }
    }
    if (hasKnownGivenNameToken) structureReasons.push("known_personal_name_token");

    if (isHeadingLike(occurrences, blocksById) && positiveReasons.length === 0) {
      return scoredResult(
        {
          reasons: [...reasons, ...positiveReasons, ...structureReasons, "heading_context"],
          explanation: "Name-like phrase, but heading context makes it less certain",
          positiveReasons: [...positiveReasons, ...structureReasons],
          filterRules: classifications,
        },
        weights,
        reviewThreshold
      );
    }
    return scoredResult(
      {
        reasons: [...reasons, ...positiveReasons, ...classifications, ...structureReasons],
        explanation: "Strong personal-name structure",
        positiveReasons: [...positiveReasons, ...structureReasons],
        filterRules: classifications,
      },
      weights,
      reviewThreshold
    );
  }

  if (tokenList.length === 1) {
    if (positiveReasons.length > 0) {
      return scoredResult(
        {
          reasons: [...reasons, ...positiveReasons, ...classifications, "single_name_candidate"],
          explanation: "Single-name candidate",
          positiveReasons,
          filterRules: classifications,
        },
        weights,
        reviewThreshold
      );
    }
    return scoredResult(
      {
        reasons: [...reasons, ...classifications, "single_token_reviewable_without_negative_evidence"],
        explanation: "Single-token candidate without strong negative evidence",
        filterRules: classifications,
      },
      weights,
      reviewThreshold
    );
  }

  return scoredResult(
    {
      reasons: [...reasons, ...positiveReasons, ...classifications, "weak_name_structure"],
      explanation: "Possible person candidate",
      suggestedType,
      positiveReasons,
      filterRules: classifications,
    },
    weights,
    reviewThreshold
  );
}
