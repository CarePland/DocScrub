// ---- Text normalization helpers (candidate_quality.py lines 281-298, 651-661) ---

// def normalize_lexicon_entry(value: str) -> str:
// Deviation (same one already recorded in phase-4-findings.md): Python's
// str.casefold() is slightly more aggressive than JS's toLowerCase() for a
// handful of non-ASCII characters (e.g. German "ß" -> "ss"). Every fixture
// and lexicon entry in scope is ASCII-range; not worth a hand-rolled
// casefold table against zero observed impact.
function normalizeLexiconEntry(value: string): string {
  const normalized = value.normalize("NFKC").replace(/[’‘`]/g, "'");
  return normalized.toLowerCase().trim();
}

// def _normalized_text(text: str) -> str:
function normalizedText(text: string): string {
  return normalizeLexiconEntry(text).replace(/\s+/g, " ");
}

// def _tokens(text: str) -> list[str]:
function tokens(text: string): string[] {
  return text.normalize("NFKC").match(TOKEN_RE) ?? [];
}

// def _normalized_token_set(text: str) -> set[str]:
function normalizedTokenSet(text: string): Set<string> {
  const set = new Set<string>();
  for (const token of tokens(text)) {
    set.add(normalizeLexiconEntry(token).replace(/^\.+|\.+$/g, ""));
  }
  return set;
}

