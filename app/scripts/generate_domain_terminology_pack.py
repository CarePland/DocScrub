#!/usr/bin/env python3
"""
generate_domain_terminology_pack.py -- generates the production runtime assets
for provenance-carrying DOMAIN TERMINOLOGY reference packs (AG, 2026-08-10).

    python3 scripts/generate_domain_terminology_pack.py finance       <csv>
    python3 scripts/generate_domain_terminology_pack.py legal         <csv>
    python3 scripts/generate_domain_terminology_pack.py employment_hr <csv>
    python3 scripts/generate_domain_terminology_pack.py government_public_admin <csv>

ONE GENERATOR, FOUR PACKS -- AND WHY THAT IS NOT PREMATURE
    `generate_higher_ed_terminology.py` is a per-asset script, matching the
    repo's convention (census, GNIS, quality dictionaries each have their
    own). This one is shared because the Finance/Accounting/Tax and Legal
    packs arrived together with the SAME row model, and writing the identical
    interning/TSV emitter twice would guarantee the two copies drift. The
    Employment/HR pack (AG, 2026-08-10) arrived third with that same row
    model and is generated here for the same reason -- it added a PACKS entry
    and nothing else structural, which is the outcome this shape was for.
    What differs between them is data-shaped and lives in PACKS below:

        normalization policy   (per source methodology -- see below)
        sub-domain column      (finance has FINANCE/ACCOUNTING/TAX; legal none)
        extra columns          (finance: source_id, acronym, acronym_expansion)
        provenance merging     (legal merges co-attesting sources into one row
                                with `|`-separated fields; finance does not)
        licensing table        (employment_hr ships per-source tier/licence/
                                retrieval columns; emitted as a side table
                                rather than folded into `notes`, so the
                                shared row contract is untouched)
        authority table        (government_public_admin names the authority
                                behind each machine source-family key; same
                                side-table treatment, same reason)
        constant columns       (government_public_admin's `jurisdiction` never
                                varies, so it is one exported constant rather
                                than 412 copies -- and the generator STOPS if
                                a later revision makes it vary, because that
                                would be a shared-contract change)

    The Government/Public Administration pack (AG, 2026-08-10) arrived fourth
    on the same row model. It needed two new PACKS keys and no change to the
    row contract, the intern tables, or any other pack's shipped asset -- which
    is the property this shape exists to keep while several packs are being
    integrated concurrently.

    Higher-ed is deliberately NOT regenerated by this script. Its asset is
    shipped, verified and shaped slightly differently; migrating it is a
    separate, mechanical change and there was no reason to couple the two.

NORMALIZATION -- REPRODUCED, NOT REINVENTED
    `normalized_term` in each CSV was produced by that dataset's own
    generator. This script re-derives it from `term` with the rules its
    methodology documents and ASSERTS equality on EVERY row. If an assertion
    fires, the TypeScript normalizer in the corresponding provider -- a second
    implementation of the same steps -- would silently disagree with the
    shipped keys and lookups would quietly miss. That is a class of bug no
    type checker catches, so it is caught here instead.

    Verified at time of writing: finance 710/710, legal 445/445,
    employment_hr 267/267, government_public_admin 412/412.

    finance (docscrub_finance_accounting_tax_methodology.md, §Normalization)
        1. NFKC
        2. curly quotes -> ASCII
        3. unicode dashes/minus -> ASCII hyphen
        4. casefold
        5. collapse whitespace, trim
        6. PUNCTUATION PRESERVED -- `Form 10-K` must not become `Form 10K`.
           Hyphenation alternates are shipped as explicit derived rows.

    legal (docscrub_legal_terms_methodology.md, §Deterministic normalization)
        steps 1-5 identical, then
        6. remove spaces immediately around `/` and `-`
        7. all other punctuation preserved

    employment_hr (docscrub_employment_hr_methodology.md, §Normalization)
        the SAME six steps as finance, arrived at independently by that
        pack's own methodology. It is aliased rather than merged below,
        because two packs agreeing today is not a reason to give them one
        normalizer they would then have to share forever: a later revision of
        either methodology must be able to move without dragging the other.
        The alias is asserted against all 267 shipped keys like every other.

    government_public_admin (docscrub_government_public_admin_methodology.md,
                             §Deterministic normalization)
        the SAME seven steps as legal, arrived at independently, and aliased
        rather than merged for the same reason. NOTE that step 6 is INERT on
        the v1 data -- no shipped row has a space next to `/` or `-`, so the
        finance policy would reproduce all 412 keys as well. It is implemented
        because the contract says so, and the verification suite exercises it
        with a synthetic input so it cannot rot unnoticed.

    All four differ from higher-ed (every non-alphanumeric run -> SPACE) and
    from census (punctuation stripped to nothing). Those differences are forced
    by the data, are documented in each provider, and are NOT to be unified.

WHAT A MATCH LICENSES
    Exactly one sentence: "this phrase is attested <domain> terminology."
    NOT a semantic type, NOT a Keep, and NOT evidence of non-personhood. The
    Legal pack contains `Doe`, `Judge`, `Levy`, `answer`, `brief` and
    `record`; the Finance pack contains `basis`, `trust`, `security`,
    `interest` and `margin`; the Employment/HR pack contains `Grade`,
    `detail`, `series`, `transfer` and `appeal`. Several are Census-attested
    personal names. Any consumer that reads membership as a person-suppressor
    reintroduces the exact failure the Census experiment already measured and
    rejected.

WHY EVERY ROW SURVIVES, AND WHY LEGAL'S MERGED ROWS ARE UN-MERGED
    52 finance keys are attested by more than one row -- `account balance` by
    Treasury/USSGL as ACCOUNTING and by the FDIC as FINANCE. The Legal pack
    instead merges co-attesting sources into ONE row with `|`-separated
    source_name/url/family/authority (4 rows do this). This script EXPANDS
    those back into one attestation per source, so both packs present the
    identical runtime shape: a key maps to a list of single-source
    attestations. That is un-merging what the pack merged, not fabrication --
    the segment counts are asserted equal across all four piped columns.

OUTPUT
    src/engines/knowledge/finance-accounting-tax-terminology.data.ts
    src/engines/knowledge/legal-terminology.data.ts
    src/engines/knowledge/employment-hr-terminology.data.ts
    src/engines/knowledge/government-public-admin-terminology.data.ts

    Format is `DomainReferencePackAsset` from
    src/engines/knowledge/DomainReferenceEvidence.ts -- intern tables plus a
    TAB-separated row block. Intern-table ORDER IS LOAD-BEARING.
"""

