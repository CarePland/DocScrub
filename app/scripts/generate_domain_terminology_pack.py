QUOTES = {"\u2018": "'", "\u2019": "'", "\u201a": "'", "\u201b": "'",
          "\u201c": '"', "\u201d": '"', "\u201e": '"', "\u201f": '"'}
DASHES = {"\u2010": "-", "\u2011": "-", "\u2012": "-", "\u2013": "-",
          "\u2014": "-", "\u2015": "-", "\u2212": "-"}


def _base(text):
    """Steps 1-5, shared by both packs' documented policies."""
    text = unicodedata.normalize("NFKC", text)
    text = "".join(QUOTES.get(c, DASHES.get(c, c)) for c in text)
    text = text.casefold()
    return re.sub(r"\s+", " ", text).strip()


def normalize_finance(term):
    return _base(term)


def normalize_legal(term):
    return re.sub(r"\s*([/-])\s*", r"\1", _base(term))


def normalize_employment_hr(term):
    """Deliberately a separate name for the same six steps -- see the module
    docstring. Aliasing documents that the agreement is a measured fact about
    two methodologies, not a shared dependency between two packs."""
    return _base(term)


def normalize_government(term):
    """Same seven steps the Legal methodology documents, arrived at
    independently by the Government/Public Administration methodology
    (§Deterministic normalization, steps 1-8). Separately named for the same
    reason `normalize_employment_hr` is: two methodologies agreeing today is a
    measured fact, not a shared dependency that would force a later revision
    of one to drag the other.

    STEP 6 IS INERT ON THE v1 DATA and is implemented anyway. No shipped
    government row contains a space adjacent to `/` or `-`, so the finance
    policy would reproduce all 412 keys too. The contract is what is
    implemented, not the accident of what this snapshot happens to exercise --
    a v2 row written `pre - award` must key the same as `pre-award`, and the
    verification suite pins that behaviour with a synthetic input rather than
    letting it rot undetected."""
    return re.sub(r"\s*([/-])\s*", r"\1", _base(term))


