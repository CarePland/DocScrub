def ts_string(value):
    escaped = (value.replace("\\", "\\\\").replace('"', '\\"')
                    .replace("\n", "\\n").replace("\r", "").replace("\t", "\\t"))
    return f'"{escaped}"'


def chunked_literal(parts, name, exported=True):
    """Emit a long string as concatenated chunks -- one huge source literal
    trips editors and some toolchains, and this costs nothing at runtime."""
    body = " +\n  ".join(ts_string(p) for p in parts)
    return f"{'export ' if exported else ''}const {name} =\n  {body};\n"


def main(pack_key, csv_path):
    if pack_key not in PACKS:
        raise SystemExit(f"unknown pack {pack_key!r}; expected one of {sorted(PACKS)}")
    pack = PACKS[pack_key]
    normalize = pack["normalize"]

    with open(csv_path, newline="", encoding="utf-8") as handle:
        source_rows = list(csv.DictReader(handle))
    if not source_rows:
        raise SystemExit(f"{csv_path}: no rows")

    # ---- NORMALIZATION PARITY. The whole point of generating rather than
    # hand-writing: if the documented policy does not reproduce the shipped
    # keys, stop, because the runtime normalizer implements that same policy.
    mismatches = [(r["term"], r["normalized_term"], normalize(r["term"]))
                  for r in source_rows if normalize(r["term"]) != r["normalized_term"]]
    if mismatches:
        for term, shipped, derived in mismatches[:20]:
            print(f"  NORMALIZATION MISMATCH {term!r}: csv={shipped!r} derived={derived!r}")
        raise SystemExit(f"{len(mismatches)} of {len(source_rows)} rows do not reproduce "
                         f"normalized_term under the documented policy -- refusing to generate.")

    # ---- Expand legal's `|`-merged provenance into one attestation per source.
    attestations = []
    for row in source_rows:
        names = [row["source_name"]]
        urls = [row["source_url"]]
        families = [row["source_family"]]
        authorities = [row["source_authority_level"]]
        if pack["merged_provenance"] and "|" in row["source_name"]:
            names = [s.strip() for s in row["source_name"].split("|")]
            urls = [s.strip() for s in row["source_url"].split("|")]
            families = [s.strip() for s in row["source_family"].split("|")]
            authorities = [s.strip() for s in row["source_authority_level"].split("|")]
            if not (len(names) == len(urls) == len(families) == len(authorities)):
                raise SystemExit(f"{row['term']!r}: piped provenance columns disagree on segment count "
                                 f"({len(names)}/{len(urls)}/{len(families)}/{len(authorities)})")
        sub_column = pack["sub_domain_column"]
        for name, url, family, authority in zip(names, urls, families, authorities):
            attestations.append({
                "normalized": row["normalized_term"],
                "term": row["term"],
                "hints": row["semantic_hint"].strip(),
                "sub_domain": (row.get(sub_column) or "").strip() if sub_column else "",
                "source": (name.strip(), url.strip(), family.strip(), authority.strip()),
                "source_id": (row.get("source_id") or "").strip(),
                "source_attested": row["source_attested"].strip().lower() == "true",
                "derived_variant": row["derived_variant"].strip().lower() == "true",
                "parent_term": (row.get("parent_term") or "").strip(),
                "risk": row["collision_risk"].strip(),
                "acronym": (row.get("acronym") or "").strip(),
                "acronym_expansion": (row.get("acronym_expansion") or "").strip(),
                "notes": (row.get("notes") or "").strip(),
            })

    # ---- LICENSING SIDE TABLE, for packs that ship licensing columns.
    # Asserted constant per source family: if a pack ever attaches two
    # different licences to one family, that is a real fact about the data
    # and the side-table shape is wrong for it -- stop rather than silently
    # keep whichever row sorted last.
    licensing = bool(pack.get("licensing_columns"))
    licensing_rows = []
    if licensing:
        by_family = {}
        for row in source_rows:
            family = row["source_family"].strip()
            entry = (row.get("source_tier", "").strip(),
                     row.get("license_status", "").strip(),
                     row.get("retrieval_date", "").strip())
            if by_family.setdefault(family, entry) != entry:
                raise SystemExit(f"source family {family!r} carries more than one "
                                 f"tier/licence/retrieval combination: "
                                 f"{by_family[family]} vs {entry}")
        licensing_rows = [(f, *by_family[f]) for f in sorted(by_family)]

    # ---- AUTHORITY SIDE TABLE. Same shape and same reasoning as the
    # licensing table: a value that is constant per source family is stored
    # once per family, not once per row. This one exists because a source
    # family is a machine key (`NARA_RM`, `FAR_PART_2`) and an audit trail has
    # to be able to name the authority behind it in words.
    authority_column = pack.get("authority_column")
    authority_rows = []
    if authority_column:
        by_family = {}
        for row in source_rows:
            family = row["source_family"].strip()
            authority = (row.get(authority_column) or "").strip()
            if by_family.setdefault(family, authority) != authority:
                raise SystemExit(f"source family {family!r} carries more than one authority: "
                                 f"{by_family[family]!r} vs {authority!r} -- a per-family side "
                                 f"table is the wrong shape for that and would drop one.")
        authority_rows = [(f, by_family[f]) for f in sorted(by_family)]

    # ---- PACK-LEVEL CONSTANT COLUMNS. A column that never varies is a fact
    # about the DATASET, not about a phrase, and is emitted once. The assert
    # is the point: the day a pack ships a second value here, this stops
    # rather than silently keeping whichever row it saw first, and whoever is
    # holding it has to decide to widen the shared row contract on purpose.
    constant_column = pack.get("jurisdiction_column")
    constant_value = None
    if constant_column:
        values = {(r.get(constant_column) or "").strip() for r in source_rows}
        if len(values) != 1:
            raise SystemExit(f"{constant_column} is not constant across the pack ({sorted(values)}) -- "
                             f"it can no longer be a pack-level constant and must become a row column "
                             f"in DomainReferencePackAsset, which changes every pack's asset.")
        constant_value = values.pop()

    # Sorted by key, then by original CSV order within a key -- stable output,
    # so a regeneration with unchanged input produces a byte-identical file.
    attestations.sort(key=lambda a: a["normalized"])

    # ---- Intern tables. ORDER IS LOAD-BEARING once shipped.
    hint_sets = sorted({a["hints"] for a in attestations})
    sub_domains = [""] + sorted({a["sub_domain"] for a in attestations} - {""})
    sources = sorted({a["source"] for a in attestations})
    strings = [""] + sorted(
        {a[k] for a in attestations for k in ("source_id", "parent_term", "acronym", "acronym_expansion", "notes")} - {""}
    )
    risks = ["LOW", "MEDIUM", "HIGH"]

    hint_index = {v: i for i, v in enumerate(hint_sets)}
    sub_index = {v: i for i, v in enumerate(sub_domains)}
    source_index = {v: i for i, v in enumerate(sources)}
    string_index = {v: i for i, v in enumerate(strings)}

    lines = []
    for a in attestations:
        if a["risk"] not in risks:
            raise SystemExit(f"{a['term']!r}: unexpected collision_risk {a['risk']!r}")
        if "\t" in a["term"] or "\t" in a["normalized"]:
            raise SystemExit(f"{a['term']!r}: TAB in a value would corrupt the row block")
        lines.append("\t".join([
            a["normalized"],
            a["term"],
            str(hint_index[a["hints"]]),
            str(sub_index[a["sub_domain"]]),
            str(source_index[a["source"]]),
            str(string_index[a["source_id"]]),
            "1" if a["source_attested"] else "0",
            "1" if a["derived_variant"] else "0",
            str(string_index[a["parent_term"]]),
            str(risks.index(a["risk"])),
            str(string_index[a["acronym"]]),
            str(string_index[a["acronym_expansion"]]),
            str(string_index[a["notes"]]),
        ]))

    keys = {a["normalized"] for a in attestations}
    multi = sum(1 for _, n in Counter(a["normalized"] for a in attestations).items() if n > 1)
    derived_count = sum(1 for a in attestations if a["derived_variant"])
    risk_counts = Counter(a["risk"] for a in attestations)
    domain_counts = Counter(a["sub_domain"] for a in attestations if a["sub_domain"])
    family_counts = Counter(a["source"][2] for a in attestations)

    P = pack["prefix"]
    domain_line = ("\n * SUB-DOMAINS: " + ", ".join(f"{k} {v}" for k, v in sorted(domain_counts.items())) + "."
                   if domain_counts else "")
    header = f'''/**
 * {Path(pack["out"]).name} -- GENERATED. DO NOT HAND-EDIT.
 *
 * Regenerate with:
 *     python3 scripts/generate_domain_terminology_pack.py {pack_key} <csv>
 * Source CSV is versioned at investigation/data/{Path(csv_path).name}.
 *
 * SOURCE: {pack["sources_blurb"]}
 *
 * CONTENT: {len(attestations)} attestation rows over {len(keys)} distinct
 * normalized terms. {multi} terms are attested by more than one row and every
 * such row is retained -- corroboration across independent source families is
 * evidence a future combination layer will want, and collapsing to a key set
 * would destroy it. {derived_count} rows are mechanically derived variants rather
 * than direct source labels. Collision risk: LOW {risk_counts["LOW"]},
 * MEDIUM {risk_counts["MEDIUM"]}, HIGH {risk_counts["HIGH"]}.{domain_line}
 *
 * THE ONE CLAIM A MATCH LICENSES: "this phrase is attested {pack["noun"]}."
 * Not a semantic type, not a Keep, and NOT evidence of non-personhood --
 * {pack["collision_blurb"]}.
 *
 * REPRESENTATION: `DomainReferencePackAsset` (see DomainReferenceEvidence.ts
 * for the column contract). Intern tables plus a TAB-separated row block,
 * sorted by normalized key then source order. Intern-table order is
 * load-bearing: regenerating with a different order invalidates every row.
 */

import type {{ DomainReferencePackAsset }} from "./DomainReferenceEvidence.js";

export const {P}_SOURCE = "{pack["version"]}";
export const {P}_ROW_COUNT = {len(attestations)};
export const {P}_TERM_COUNT = {len(keys)};

/** Pipe-separated hint combinations, verbatim from the source dataset.
 *  Index-addressed by row column 2. Order is load-bearing. */
const HINT_SETS: readonly string[] = [
{chr(10).join("  " + ts_string(v) + "," for v in hint_sets)}
];

/** Index-addressed by row column 3. Index 0 is "" -- no sub-domain. */
const SUB_DOMAINS: readonly string[] = [
{chr(10).join("  " + ts_string(v) + "," for v in sub_domains)}
];

/** Index-addressed by row column 4: [name, url, family, authorityLevel]. */
const SOURCES: readonly (readonly [string, string, string, string])[] = [
{chr(10).join("  [" + ", ".join(ts_string(x) for x in v) + "]," for v in sources)}
];

/** Shared pool for the sparse columns (source ids, parent terms, acronyms,
 *  acronym expansions, notes). Index 0 is "". */
const STRINGS: readonly string[] = [
{chr(10).join("  " + ts_string(v) + "," for v in strings)}
];

'''

    out_path = ROOT / pack["out"]
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as out:
        out.write(header)
        per_piece = 200
        groups = [lines[i:i + per_piece] for i in range(0, len(lines), per_piece)]
        parts = ["\n".join(g) + ("\n" if n < len(groups) - 1 else "") for n, g in enumerate(groups)]
        out.write("/** One line per attestation row, TAB-separated. Columns, in order:\n"
                  " *  normalized, term, hintSetIdx, subDomainIdx, sourceIdx, sourceIdIdx,\n"
                  " *  sourceAttested(0|1), derivedVariant(0|1), parentIdx, riskIdx,\n"
                  " *  acronymIdx, acronymExpIdx, notesIdx */\n")
        out.write(chunked_literal(parts, "ROWS", exported=False))
        if licensing:
            out.write(f'''
/**
 * SOURCE LICENSING AND RETRIEVAL, one row per source family:
 *   [sourceFamily, sourceTier, licenseStatus, retrievalDate]
 *
 * `sourceTier` is "" for packs whose dataset ships no tier grade; the licence
 * and retrieval date are what every such pack carries and they are the two
 * that matter for redistribution.
 *
 * A SIDE TABLE, not a row column, for two reasons. These values are constant
 * per source family in the dataset (the generator asserts it), so per-row
 * storage would be {len(attestations)} copies of {len(licensing_rows)} facts. And
 * licensing is provenance ABOUT a dataset, not evidence about a phrase --
 * folding it into `notes` would put it in front of reviewers, who are reading
 * that field to judge a candidate.
 *
 * Downstream redistribution should carry this attribution forward.
 */
export const {P}_SOURCE_LICENSING: readonly (readonly [string, string, string, string])[] = [
{chr(10).join("  [" + ", ".join(ts_string(x) for x in v) + "]," for v in licensing_rows)}
];
''')
        if authority_rows:
            out.write(f'''
/**
 * SOURCE AUTHORITY, one row per source family: [sourceFamily, authority]
 *
 * The source family is the machine key an attestation carries; this names the
 * body behind it in the words the dataset used. Constant per family (the
 * generator asserts it), so it is stored once per family rather than
 * {len(attestations)} times. An audit path that wants to print "why does DocScrub
 * say this is {pack["noun"]}" resolves it here.
 */
export const {P}_SOURCE_AUTHORITIES: readonly (readonly [string, string])[] = [
{chr(10).join("  [" + ", ".join(ts_string(x) for x in v) + "]," for v in authority_rows)}
];
''')
        if constant_value is not None:
            out.write(f'''
/**
 * The `{constant_column}` every row in this pack carries -- asserted
 * single-valued at generation. A pack-level constant rather than a row
 * column, because storing one value {len(attestations)} times would have meant
 * widening `DomainReferencePackAsset` and regenerating every other pack's
 * asset to carry a field that does not vary.
 *
 * IF A LATER VERSION OF THIS DATASET VARIES IT, the generator stops. That is
 * deliberate: the conversion to a row column is a shared-contract change and
 * should be a decision, not a silent widening.
 */
export const {P}_{constant_column.upper()} = {ts_string(constant_value)};
''')
        out.write(f'''
/** The pack asset. Consumed by {pack["consumer"]}.ts,
 *  which owns this pack's normalization policy and its evidence contract. */
export const {P}_PACK: DomainReferencePackAsset = {{
  source: {P}_SOURCE,
  rowCount: {P}_ROW_COUNT,
  termCount: {P}_TERM_COUNT,
  rows: ROWS,
  hintSets: HINT_SETS,
  subDomains: SUB_DOMAINS,
  sources: SOURCES,
  strings: STRINGS,
}};
''')

    size = out_path.stat().st_size
    print(f"wrote {out_path.relative_to(ROOT)} ({size / 1024:.0f} KiB)")
    print(f"  csv rows={len(source_rows)}  attestations={len(attestations)}  keys={len(keys)}  "
          f"multi-provenance={multi}  derived={derived_count}")
    print(f"  interned: hintSets={len(hint_sets)} subDomains={len(sub_domains)} "
          f"sources={len(sources)} strings={len(strings)}")
    print(f"  collision risk: " + "  ".join(f"{k}={risk_counts[k]}" for k in risks))
    if domain_counts:
        print(f"  sub-domains: " + "  ".join(f"{k}={v}" for k, v in sorted(domain_counts.items())))
    print(f"  source families: " + "  ".join(f"{k}={v}" for k, v in sorted(family_counts.items())))
    print(f"  normalization parity: {len(source_rows)}/{len(source_rows)} rows reproduce normalized_term")


